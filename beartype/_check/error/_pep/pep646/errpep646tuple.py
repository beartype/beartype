'''
Beartype :pep:`646`-compliant **tuple type hint violation finders** (i.e.,
functions returning human-readable strings explaining violations of
:pep:`646`-compliant fixed-variadic tuple type hints).

This private submodule is *not* intended for importation by downstream callers.
'''

# ....................{ IMPORTS                            }....................
from beartype._check.cls.hint.tree.hinttreeerror import HintTreeError
from beartype._check.error._nonpep.errnonpeptype import (
    find_cause_type_instance_origin)
from beartype._data.hint.sign.datahintsigns import (
    HintSignPep646TupleFixedVariadic)
from beartype._util.hint.pep.proposal.pep646.pep484585646tuple import (
    get_hint_pep646_tuple_fixed_variadic_args)
from beartype._util.text.utiltextansi import color_type
from beartype._util.text.utiltextprefix import prefix_pith_type
from beartype._util.text.utiltextrepr import represent_pith
from itertools import chain

# ....................{ FINDERS                            }....................
def find_cause_pep646_tuple_fixed_variadic(
    cause: HintTreeError,
) -> HintTreeError:
    '''
    Output cause describing whether the pith of the passed input cause either
    satisfies or violates the :pep:`646`-compliant **fixed-variadic tuple hint**
    of that cause.

    This finder type-checks the same items as the code generated by the
    :func:`beartype._check.code._pep.pep646.codepep646tuple.make_hint_pep646_tuple_check_expr`
    factory, including the same pseudo-random variadic item.

    Parameters
    ----------
    cause : HintTreeError
        Input violation cause finder to be inspected.

    Returns
    -------
    HintTreeError
        Output violation cause finder type-checking this input.
    '''
    assert isinstance(cause, HintTreeError), f'{repr(cause)} not cause.'
    assert cause.hint_curr.hint_sign is HintSignPep646TupleFixedVariadic, (
        f'{repr(cause.hint_curr.hint_sign)} not '
        f'"HintSignPep646TupleFixedVariadic".'
    )

    # ....................{ VIOLATE ~ shallow              }....................
    # Shallow output cause describing the failure of this pith to be a tuple if
    # this pith is not a tuple *OR* "None" otherwise.
    cause_shallow = find_cause_type_instance_origin(cause)

    # If this pith is *NOT* a tuple, return this shallow cause.
    if cause_shallow.cause_str_or_none is not None:
        return cause_shallow
    # Else, this pith is a tuple.

    # ....................{ LOCALS                         }....................
    # Prefix, variadic, and suffix child hints subscripting this tuple hint.
    #
    # Note that this finder intentionally avoids the "cause.hint_childs_sane"
    # property, which would erroneously sanify the unpacked child hint
    # subscripting this hint (e.g., "*tuple[str, ...]") as a standalone hint.
    hints_prefix, hint_variadic, hints_suffix = (
        get_hint_pep646_tuple_fixed_variadic_args(cause.hint_curr_sanified)
    )

    # Number of prefix child hints, fixed (i.e., prefix and suffix) child hints,
    # items in this tuple, and variadic items in this tuple.
    hints_prefix_len = len(hints_prefix)
    hints_fixed_len = hints_prefix_len + len(hints_suffix)
    pith_len = len(cause.pith)
    pith_variadic_len = pith_len - hints_fixed_len

    # ....................{ VIOLATE ~ length               }....................
    # If this tuple is shorter than the minimum length, return a deep output
    # cause describing this failure.
    if pith_variadic_len < 0:
        return cause.permute_cause(
            cause_str_or_none=(
                f'{represent_pith(cause.pith)} length '
                f'{pith_len} < {hints_fixed_len}'
            ),
        )
    # Else, this tuple is at least the minimum length.

    # ....................{ VIOLATE ~ items                }....................
    # 0-based index of the variadic item of this tuple type-checked by the
    # parent @beartype-generated wrapper function: either a pseudo-random
    # variadic item if that wrapper generated a pseudo-random integer *OR* the
    # first variadic item otherwise. That wrapper generates *NO* such integer
    # only if either randomized type-checking is disabled *OR* the variadic
    # child hint is ignorable, in which case any variadic item suffices.
    pith_variadic_index = hints_prefix_len + (
        cause.random_int % pith_variadic_len
        if cause.random_int is not None and pith_variadic_len else
        0
    )

    # For the index of each item of this tuple type-checked by that wrapper and
    # the possibly ignorable insane child hint type-checking that item (i.e.,
    # each prefix item, each suffix item, and one variadic item if any)...
    for pith_item_index, hint_child in chain(
        enumerate(hints_prefix),
        enumerate(hints_suffix, pith_len - len(hints_suffix)),
        ((pith_variadic_index, hint_variadic),) if pith_variadic_len else (),
    ):
        # Deep output cause type-checking whether this item satisfies this hint.
        cause_deep = cause.permute_cause_hint_child_insane(
            hint_child_insane=hint_child, pith=cause.pith[pith_item_index],
        ).find_cause()

        # If this item is the cause of this failure...
        if cause_deep.cause_str_or_none is not None:
            # Human-readable substring prefixing this failure with metadata
            # describing this item.
            cause_deep.cause_str_or_none = (
                f'{prefix_pith_type(pith=cause.pith, is_color=cause.conf.is_color)}'
                f'index {color_type(text=str(pith_item_index), is_color=cause.conf.is_color)} '
                f'item {cause_deep.cause_str_or_none}'
            )

            # Return this cause.
            return cause_deep
        # Else, this item is *NOT* the cause of this failure.

    # Return this cause as is. Since *ALL* type-checked items of this tuple are
    # valid, this pith deeply satisfies this hint.
    return cause
